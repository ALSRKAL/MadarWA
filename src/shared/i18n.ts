export const resources = {
  ar: { translation: ar },
  en: { translation: en },
} as const;

let initialized = false;

export function initI18n(language: Language): typeof i18n {
  if (!initialized) {
    initialized = true;
    void i18n.init({
      resources,
      lng: language,
      fallbackLng: "en",
      initAsync: false,
      interpolation: { escapeValue: false },
      returnNull: false,
    });
  } else if (i18n.language !== language) {
    void i18n.changeLanguage(language);
  }
  return i18n;
}

export function tFor(language: Language): (key: string, variables?: Record<string, unknown>) => string {
  // Safe in any execution order: the first translation initializes i18next.
  initI18n(language);
  const translate = i18n.getFixedT(language);
  return (key, variables) => String(translate(key, variables as never));
}

export function dirFor(language: Language): "rtl" | "ltr" {
  return language === "ar" ? "rtl" : "ltr";
}

